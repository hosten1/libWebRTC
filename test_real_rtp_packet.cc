// 安全的内存拷贝函数，避免越界
void SafeMemcpy(uint8_t* dest, const uint8_t* src, size_t n, size_t dest_max) {
    if (n > dest_max) {
        std::cerr << "ERROR: memcpy would overflow destination buffer! size=" << n
                  << ", max=" << dest_max << std::endl;
        return;
    }
    memcpy(dest, src, n);
}

